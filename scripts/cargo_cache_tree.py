"""Seed and protect immutable Cargo snapshots and writable run-local copies."""

from __future__ import annotations

import errno
import shutil
import stat
import tomllib
import typing as typ

if typ.TYPE_CHECKING:
    from pathlib import Path

_CARGO_HOME_CACHE_TREES = {
    "registry": ("cache", "index"),
    "git": ("db",),
}
_CARGO_HOME_CONFIG_FILES = (
    "config",
    "config.toml",
    "credentials",
    "credentials.toml",
)


def seed_cargo_home(
    source: Path,
    destination: Path,
    error_type: type[Exception],
) -> None:
    """Copy reusable cache data and Cargo settings into the staging home.

    Extracted registry sources and Git checkouts are regenerated by the locked
    fetch. Snapshot preparation prunes registry archives to the package names
    and versions selected by the lockfile; registry indexes and Git databases
    remain copied cache metadata.

    Parameters
    ----------
    source : Path
        Caller Cargo home supplying reusable cache and settings.
    destination : Path
        Staging Cargo home receiving independent writable copies.
    error_type : type of Exception
        Exception class to raise when a source entry is a symlink.

    Raises
    ------
    error_type
        If a cache tree or configuration file is a symlink.
    OSError
        If cache data or configuration files cannot be copied.
    """  # ruff: ignore[docstring-extraneous-exception] - caller-selected validation and filesystem errors propagate from copy helpers.
    if not source.exists():
        return
    _copy_cache_trees(source, destination, error_type)
    _copy_configuration_files(source, destination, error_type)


def _copy_cache_trees(
    source: Path,
    destination: Path,
    error_type: type[Exception],
) -> None:
    """Copy registry and Git cache trees without following shared links."""
    for directory, entries in _CARGO_HOME_CACHE_TREES.items():
        for name in entries:
            source_entry = source / directory / name
            if not source_entry.exists():
                continue
            if source_entry.is_symlink():
                msg = f"Cargo cache source must not be a symlink: {source_entry}"
                raise error_type(msg)
            reject_tree_symlinks(source_entry, error_type)
            shutil.copytree(source_entry, destination / directory / name)


def _copy_configuration_files(
    source: Path,
    destination: Path,
    error_type: type[Exception],
) -> None:
    """Copy caller settings and credentials without following shared links."""
    for name in _CARGO_HOME_CONFIG_FILES:
        source_entry = source / name
        if not source_entry.exists():
            continue
        if source_entry.is_symlink():
            msg = f"Cargo configuration must not be a symlink: {source_entry}"
            raise error_type(msg)
        shutil.copy2(source_entry, destination / name)


def _prune_registry_archives(cargo_home: Path, lockfile: Path) -> None:
    """Remove cached registry archives that the lockfile does not select."""
    lock = tomllib.loads(lockfile.read_text(encoding="utf-8"))
    selected_archives = {
        f"{package['name']}-{package['version']}.crate"
        for package in lock.get("package", [])
        if str(package.get("source", "")).startswith(("registry+", "sparse+"))
    }
    cache_root = cargo_home / "registry" / "cache"
    for archive in cache_root.glob("*/*.crate"):
        if archive.name not in selected_archives:
            archive.unlink()


def publish_snapshot(temporary_path: Path, snapshot_path: Path) -> bool:
    """Publish a complete snapshot with one same-filesystem rename.

    Parameters
    ----------
    temporary_path : Path
        Complete staging directory on the snapshot filesystem.
    snapshot_path : Path
        Destination path for the published snapshot.

    Returns
    -------
    bool
        ``True`` when this caller publishes the snapshot; ``False`` when
        another caller already published a real directory at that path.

    Raises
    ------
    OSError
        If rename fails for a reason other than another caller winning the
        publication race with a real directory.
    """
    try:
        temporary_path.rename(snapshot_path)
    except OSError as error:
        lost_race = error.errno in {errno.EEXIST, errno.ENOTEMPTY}
        if lost_race and _is_real_directory(snapshot_path):
            return False
        raise
    return True


def _is_real_directory(path: Path) -> bool:
    """Reject symlink destinations when identifying a snapshot race winner."""
    return path.is_dir() and not path.is_symlink()


def make_tree_read_only(root: Path) -> None:
    """Remove write permissions before exposing a snapshot to other runs.

    Parameters
    ----------
    root : Path
        Snapshot root whose regular files and directories become read-only.

    Raises
    ------
    OSError
        If an entry cannot be inspected or its permissions cannot be changed.
    """  # ruff: ignore[docstring-extraneous-exception] - filesystem errors propagate from Path.stat and Path.chmod.
    paths = sorted(root.rglob("*"), key=lambda path: len(path.parts), reverse=True)
    for path in (*paths, root):
        if path.is_symlink():
            continue
        mode = stat.S_IMODE(path.stat().st_mode)
        path.chmod(mode & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH))


def make_tree_writable(root: Path) -> None:
    """Restore owner write and traversal permissions on a private copy.

    Parameters
    ----------
    root : Path
        Run-local Cargo home whose entries are made writable by its owner.

    Raises
    ------
    OSError
        If an entry cannot be inspected or its permissions cannot be changed.
    """  # ruff: ignore[docstring-extraneous-exception] - filesystem errors propagate from Path.stat and Path.chmod.
    paths = sorted(root.rglob("*"), key=lambda path: len(path.parts), reverse=True)
    for path in (*paths, root):
        if path.is_symlink():
            continue
        mode = stat.S_IMODE(path.stat().st_mode)
        additions = stat.S_IWUSR
        if path.is_dir():
            additions |= stat.S_IXUSR
        path.chmod(mode | additions)


def reject_tree_symlinks(root: Path, error_type: type[Exception]) -> None:
    """Reject cache descendants that could redirect writes to shared files.

    Parameters
    ----------
    root : Path
        Cache tree to inspect recursively.
    error_type : type of Exception
        Exception class used when a descendant is a symbolic link.

    Raises
    ------
    error_type
        If any descendant of ``root`` is a symbolic link.
    """  # ruff: ignore[docstring-extraneous-exception] - the caller-selected exception type is raised for symlink entries.
    linked_paths = [path for path in root.rglob("*") if path.is_symlink()]
    if linked_paths:
        msg = f"Cargo cache trees must not contain symlinks: {linked_paths[0]}"
        raise error_type(msg)
